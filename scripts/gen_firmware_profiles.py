#!/usr/bin/env python3
"""Generate firmware/citycamp_edge_node/include/node_profiles.hpp from the backend fleet config.

The firmware's 10 selectable node profiles (`NODE EN-01` .. `NODE EN-10`) must describe the
exact conduit geometry, full-scale depth and transducer mount height the backend's virtual
fleet uses, so they are generated — never hand-edited. `--check` exits 1 if the committed
header is stale (used by scripts/test_phase5_firmware.py).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.twin import TwinRuntime  # noqa: E402

OUT = ROOT / "firmware" / "citycamp_edge_node" / "include" / "node_profiles.hpp"
SHAPE = {"CIRCULAR": "Shape::Circular", "RECT_CLOSED": "Shape::RectClosed", "ARCH": "Shape::Arch"}


def render() -> str:
    rt = TwinRuntime()
    rows = []
    for sid, node in rt.nodes.items():
        c = node.cfg
        meta = rt.sensors_meta[sid]
        if c.geom is not None:
            g = c.geom
            geom = f"{{{SHAPE[g.shape]}, {g.rise_m!r}, {g.span_m!r}, {g.haunch_m!r}, {g.manning_n!r}, {g.slope!r}}}"
            has = "true"
        else:
            geom, has = "{Shape::Circular, 1.0, 1.0, 0.0, 0.013, 0.01}", "false"
        rows.append(
            f'    {{"{sid}", "{c.device_eui}", {has}, {geom}, {c.full_scale_m!r}, {c.mount_mm:.1f}}},'
            f'  // {meta["name"]} -> {meta["attached_to"]}'
        )
    vbat = ", ".join(f"{n.cfg.vbat_v!r}" for n in rt.nodes.values())
    return f"""// AUTO-GENERATED by scripts/gen_firmware_profiles.py from backend/twin.py + city_camp_network.json.
// Do not edit by hand: run `python scripts/gen_firmware_profiles.py` after regenerating the network.
#pragma once

#include "edge_core.hpp"

namespace edge {{

constexpr std::size_t NODE_PROFILE_COUNT = {len(rows)};

// {{sensor_id, device_eui, has_geom, {{shape, rise_m, span_m, haunch_m, manning_n, slope}}, full_scale_m, mount_mm}}
inline const NodeConfig NODE_PROFILES[NODE_PROFILE_COUNT] = {{
{chr(10).join(rows)}
}};

// Nominal battery voltages used by the virtual fleet (bench boards measure their own).
constexpr real NODE_NOMINAL_VBAT[NODE_PROFILE_COUNT] = {{{vbat}}};

inline int find_node_profile(const char* id) {{
  for (std::size_t i = 0; i < NODE_PROFILE_COUNT; ++i) {{
    const char* a = NODE_PROFILES[i].sensor_id;
    const char* b = id;
    while (*a && *b && *a == *b) {{ ++a; ++b; }}
    if (*a == '\\0' && (*b == '\\0' || *b == ' ' || *b == '\\r' || *b == '\\n')) return static_cast<int>(i);
  }}
  return -1;
}}

}}  // namespace edge
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"STALE: {OUT.relative_to(ROOT)} (run scripts/gen_firmware_profiles.py)")
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
